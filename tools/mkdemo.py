#!/usr/bin/env python3
"""mkdemo.py - the attract-mode demo route: a walk through a map, written as src/demo_path.h.

Cube's own demos are recordings of play; this is a generated tour.  It walks the cells a player can actually walk (open,
not a door - doors start closed - no corner cells, headroom for the 4.2 unit body, steps of at most one unit), visits the
reachable map in a chain of breadth-first legs, and string-pulls each leg into straight runs.  The game follows the
polyline at walking speed; the demo player's view, aim and firing are worked out at run time.
usage: mkdemo.py map.cmp out.h [seconds]"""
import collections, math, random, struct, sys

def load(path):
    d = open(path, 'rb').read(); ss = 1 << d[4]; ne, = struct.unpack_from('<H', d, 6); b = 330 + 12 * ne
    ents = [struct.unpack_from('<hhhhBBBB', d, 330 + 12 * i) for i in range(ne)]
    cells = [struct.unpack_from('<BbbBBBBBB', d, b + 12 * i) for i in range(ss * ss)]
    return ss, ents, cells

def main():
    path, out = sys.argv[1], sys.argv[2]; secs = float(sys.argv[3]) if len(sys.argv) > 3 else 80
    ss, ents, cells = load(path)
    C = lambda x, y: cells[y * ss + x] if 0 <= x < ss and 0 <= y < ss else (0, 0, 0, 0, 0, 0, 0, 0, 0)
    def ok(x, y):                       # the cell and its 8 neighbours: open space at nearly the same floor height
        t, f, c = C(x, y)[:3]
        if t not in (2, 3, 4) or c - f < 4: return False
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                tt, ff, cc = C(x + dx, y + dy)[:3]
                if tt not in (2, 3, 4) or ff > f + 1 or cc - max(f, ff) < 4: return False
        return True
    def nbrs(c):
        x, y = c
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if ok(*n) and abs(C(*n)[1] - C(x, y)[1]) <= 1: yield n
    sp = [e for e in ents if e[4] == 2][0]
    start = min(((x, y) for y in range(ss) for x in range(ss) if ok(x, y)), key=lambda c: abs(c[0] - sp[0]) + abs(c[1] - sp[1]))
    def bfs(a):
        prev = {a: None}; q = collections.deque([a])
        while q:
            c = q.popleft()
            for n in nbrs(c):
                if n not in prev: prev[n] = c; q.append(n)
        return prev
    reach = bfs(start)
    print('reachable cells from the spawn (doors open: the demo opens them): %d' % len(reach))
    def clear(a, b):                    # straight walk a->b stays on walkable cells (checked every 1/8 cell)
        n = int(max(abs(b[0] - a[0]), abs(b[1] - a[1])) * 8) + 1
        h0 = C(int(a[0]), int(a[1]))[1]
        for i in range(n + 1):
            x = a[0] + (b[0] - a[0]) * i / n; y = a[1] + (b[1] - a[1]) * i / n
            if not ok(int(x), int(y)) or abs(C(int(x), int(y))[1] - h0) > 1: return False
            h0 = C(int(x), int(y))[1]
        return True
    rnd = random.Random(11); speed = 55 / 256.0 * 60          # cells per second (a little brisker than the player)
    pts = [(start[0] + .5, start[1] + .5)]; visited = set(); length = 0.0; cur = start
    while length < secs * speed:
        prev = bfs(cur)
        cand = [c for c in prev if c not in visited and 14 <= abs(c[0] - cur[0]) + abs(c[1] - cur[1]) <= 40]
        if not cand: cand = [c for c in prev if abs(c[0] - cur[0]) + abs(c[1] - cur[1]) >= 8]
        tgt = rnd.choice(cand)
        leg = []; c = tgt
        while c: leg.append(c); c = prev[c]
        leg = [(x + .5, y + .5) for x, y in leg[::-1]]
        for c in leg:
            for dy in range(-3, 4):
                for dx in range(-3, 4): visited.add((int(c[0]) + dx, int(c[1]) + dy))
        i = 0                            # string pulling
        while i < len(leg) - 1:
            j = len(leg) - 1
            while j > i + 1 and not clear(leg[i], leg[j]): j -= 1
            length += math.hypot(leg[j][0] - leg[i][0], leg[j][1] - leg[i][1]); pts.append(leg[j]); i = j
        cur = tgt
    with open(out, 'w') as o:
        o.write('/* generated by tools/mkdemo.py from %s: attract-mode route, %d points, %.0f cells, about %.0f s.  Units: 1/16 cell */\n' % (path.split('/')[-1], len(pts), length, length / speed))
        o.write('#define DEMO_MAP 1\n#define DEMO_NPTS %d\nstatic const int16_t demo_pts[DEMO_NPTS][2] = {\n' % len(pts))
        for i in range(0, len(pts), 8):
            o.write('\t' + ' '.join('{ %d, %d },' % (round(x * 16), round(y * 16)) for x, y in pts[i:i + 8]) + '\n')
        o.write('};\n')
    print('%d points, %.0f cells, about %.0f seconds' % (len(pts), length, length / speed))

if __name__ == '__main__': main()
